/** Which guide section explains the page at a given path. */
export const sectionForPath = (path: string): string => {
  const map: [RegExp, string][] = [
    [/^\/reception/, 'reception'], [/^\/queue/, 'queue'], [/^\/visits/, 'doctor'], [/^\/patients/, 'patients'],
    [/^\/appointments/, 'appointments'], [/^\/lab/, 'lab'], [/^\/billing\/(cashier|payments)/, 'cashier'], [/^\/billing/, 'billing'],
    [/^\/expenses/, 'cashier'], [/^\/(inventory|suppliers|purchases)/, 'inventory'], [/^\/staff/, 'staff'], [/^\/(reports|dashboard)/, 'reports'],
    [/^\/settings/, 'settings'], [/^\/audit/, 'security'],
  ];
  return map.find(([re]) => re.test(path))?.[1] ?? 'start';
};
